import re, json, unicodedata, openpyxl
from collections import OrderedDict as OD

def nz(s):  # 全角→半角、ダッシュ類を統一
    s = unicodedata.normalize('NFKC', str(s))
    return re.sub(r'[ー‐－―−–]', '-', s).strip()
TEL = re.compile(r'0\d{1,4}-\d{1,4}-\d{3,4}')

DATA = OD()
def pref(name, label, url, asof, note=''):
    DATA[name] = {"name": name, "src": {"label": label, "url": url, "asof": asof}, "note": note, "m": OD()}
    return DATA[name]["m"]
def c(label, tel, note=''):
    return {"l": label, "t": tel, "n": note}

